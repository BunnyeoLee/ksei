-- 1) 회원 정보
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null,
  name text not null,
  email text,
  phone text,
  class_year int,
  role text not null default 'member' check (role in ('member','admin','blocked')),
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;

create or replace function public.is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists(select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;
create or replace function public.my_role() returns text
language sql stable security definer set search_path = public as $$
  select role from public.profiles where id = auth.uid();
$$;

drop policy if exists "profiles_read" on public.profiles;
create policy "profiles_read" on public.profiles for select using (id = auth.uid() or public.is_admin());
drop policy if exists "profiles_update_self" on public.profiles;
create policy "profiles_update_self" on public.profiles for update
  using (id = auth.uid()) with check (id = auth.uid() and role = public.my_role());
drop policy if exists "profiles_update_admin" on public.profiles;
create policy "profiles_update_admin" on public.profiles for update using (public.is_admin());

-- 가입 시 회원 정보 자동 생성 (권한은 항상 일반 회원으로 시작)
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, username, name, email, phone, class_year)
  values (new.id,
          lower(new.raw_user_meta_data->>'username'),
          coalesce(new.raw_user_meta_data->>'name',''),
          new.email,
          new.raw_user_meta_data->>'phone',
          nullif(new.raw_user_meta_data->>'class_year','')::int);
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- 아이디 중복 확인, 아이디로 로그인
create or replace function public.username_available(p_username text) returns boolean
language sql stable security definer set search_path = public as $$
  select not exists(select 1 from public.profiles where username = lower(p_username));
$$;
create or replace function public.login_email(p_username text) returns text
language sql stable security definer set search_path = public as $$
  select email from public.profiles where username = lower(p_username) and role <> 'blocked';
$$;
grant execute on function public.username_available(text), public.login_email(text) to anon, authenticated;

-- 2) 게시글
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  board text not null check (board in ('notice','gallery','family','alumni','free','company')),
  title text not null,
  content text not null default '',
  images text[] not null default '{}',
  tag text,
  pinned boolean not null default false,
  author_id uuid references auth.users(id) on delete set null,
  author_name text,
  views int not null default 0,
  comment_count int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz
);
create index if not exists posts_board_idx on public.posts(board, pinned desc, created_at desc);
alter table public.posts enable row level security;

-- 글쓴이 이름은 서버에서 자동으로 채움(다른 사람 이름으로 위장 방지)
create or replace function public.stamp_post() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if auth.uid() is not null then
    if tg_op = 'INSERT' then
      new.author_id := auth.uid();
      new.author_name := (select name from public.profiles where id = auth.uid());
      new.views := 0; new.comment_count := 0;
    else
      new.author_id := old.author_id; new.author_name := old.author_name;
      new.views := old.views; new.comment_count := old.comment_count; new.created_at := old.created_at;
      new.updated_at := now();
    end if;
    if not public.is_admin() then new.pinned := coalesce(old.pinned, false); end if;
  end if;
  return new;
end $$;
drop trigger if exists posts_stamp on public.posts;
create trigger posts_stamp before insert or update on public.posts
  for each row execute function public.stamp_post();

drop policy if exists "posts_read" on public.posts;
create policy "posts_read" on public.posts for select using (true);
drop policy if exists "posts_insert" on public.posts;
create policy "posts_insert" on public.posts for insert to authenticated
  with check (public.my_role() in ('member','admin') and (board <> 'notice' or public.is_admin()));
drop policy if exists "posts_update" on public.posts;
create policy "posts_update" on public.posts for update to authenticated
  using ((author_id = auth.uid() and public.my_role() = 'member') or public.is_admin());
drop policy if exists "posts_delete" on public.posts;
create policy "posts_delete" on public.posts for delete to authenticated
  using (author_id = auth.uid() or public.is_admin());

create or replace function public.increment_views(p_id bigint) returns void
language sql security definer set search_path = public as $$
  update public.posts set views = views + 1 where id = p_id;
$$;
grant execute on function public.increment_views(bigint) to anon, authenticated;

-- 3) 댓글
create table if not exists public.comments (
  id bigint generated by default as identity primary key,
  post_id bigint not null references public.posts(id) on delete cascade,
  content text not null,
  author_id uuid references auth.users(id) on delete set null default auth.uid(),
  author_name text,
  created_at timestamptz not null default now()
);
alter table public.comments enable row level security;
create or replace function public.stamp_comment() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if tg_op = 'INSERT' then
    new.author_id := auth.uid();
    new.author_name := (select name from public.profiles where id = auth.uid());
    update public.posts set comment_count = comment_count + 1 where id = new.post_id;
    return new;
  else
    update public.posts set comment_count = greatest(comment_count - 1, 0) where id = old.post_id;
    return old;
  end if;
end $$;
drop trigger if exists comments_stamp_ins on public.comments;
create trigger comments_stamp_ins before insert on public.comments for each row execute function public.stamp_comment();
drop trigger if exists comments_stamp_del on public.comments;
create trigger comments_stamp_del after delete on public.comments for each row execute function public.stamp_comment();

drop policy if exists "comments_read" on public.comments;
create policy "comments_read" on public.comments for select using (true);
drop policy if exists "comments_insert" on public.comments;
create policy "comments_insert" on public.comments for insert to authenticated with check (public.my_role() in ('member','admin'));
drop policy if exists "comments_delete" on public.comments;
create policy "comments_delete" on public.comments for delete to authenticated using (author_id = auth.uid() or public.is_admin());

